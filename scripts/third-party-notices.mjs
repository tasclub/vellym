// 配布物のcli.mjsとui/はesbuild・viteで第三者コードを取り込んだ単一bundleになる。
// MIT・ISC・BSDは配布時に著作権表示とライセンス本文の保持を求めるため、
// package-lock.jsonのproduction依存からNOTICEを生成してtarballへ同梱する。
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\..*)?$/i;

async function licenseText(packageDirectory) {
  let entries;
  try {
    entries = await readdir(packageDirectory, { withFileTypes: true });
  } catch {
    return undefined;
  }
  const found = entries
    .filter((entry) => entry.isFile() && LICENSE_FILE.test(entry.name))
    .map((entry) => entry.name)
    .sort();
  if (!found.length) return undefined;
  const parts = [];
  for (const name of found) {
    const text = await readFile(path.join(packageDirectory, name), "utf8");
    parts.push(text.trim());
  }
  return parts.join("\n\n");
}

export async function generateThirdPartyNotices(root, outputFile) {
  const lock = JSON.parse(
    await readFile(path.join(root, "package-lock.json"), "utf8")
  );
  const packages = [];
  for (const [location, entry] of Object.entries(lock.packages ?? {})) {
    if (!location.startsWith("node_modules/")) continue;
    // devDependenciesは配布物へ入らない。workspace linkは自前のコード。
    if (entry.dev || entry.link) continue;
    const name = location.slice(location.lastIndexOf("node_modules/") + "node_modules/".length);
    if (name.startsWith("@vellym-internal/")) continue;
    packages.push({
      name,
      version: entry.version ?? "",
      license: entry.license ?? "",
      directory: path.join(root, location)
    });
  }
  packages.sort((left, right) => left.name.localeCompare(right.name));

  const missing = [];
  const sections = [];
  for (const item of packages) {
    const text = await licenseText(item.directory);
    if (!text) missing.push(item.name);
    const heading = `## ${item.name} ${item.version}`.trimEnd();
    const declared = item.license ? `\nLicense: ${item.license}\n` : "\n";
    sections.push(
      `${heading}\n${declared}\n${
        text
          ? `\`\`\`\n${text.replaceAll("```", "'''")}\n\`\`\``
          : "License text was not published with this package. See the package registry entry for the full terms."
      }\n`
    );
  }

  const notices = `# Third-party notices

Vellym is distributed as a bundle that embeds the third-party packages listed
below. Each package remains under its own license and copyright. This file is
generated by \`scripts/third-party-notices.mjs\` from \`package-lock.json\`.

Packages: ${packages.length}

${sections.join("\n")}`;
  await writeFile(outputFile, notices, "utf8");
  return { count: packages.length, missing };
}
